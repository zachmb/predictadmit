					Building a reach / target / safety list
				</h2>
				<p class="mt-4">
					Once you know your projected profile, sort schools by how your numbers compare to each
					one's admitted class. A balanced list isn't about prestige tiers &mdash; it's about
					probability. Here's the framework:
				</p>

				<div class="mt-6 overflow-hidden rounded-2xl border border-slate-200">
					<table class="w-full text-left text-sm">
