			<section>
				<h2 class="text-2xl font-bold tracking-tight text-slate-900">
					Why junior year is the leverage point
				</h2>
				<p class="mt-4">
					Most of what a selective college evaluates is effectively locked in by the fall of senior
					year. Your junior-year transcript is the last complete year on your application. Your
					standardized testing is usually finished by the end of junior year or early fall. The
					activities you list have to already exist. In other words, senior fall is where you
					<em>present</em> your profile &mdash; junior year is where you still get to
					<em>change</em> it.
				</p>
				<p class="mt-4">
					That's what makes a junior-year diagnostic so valuable. A weakness you spot in October of
					junior year is a fixable problem: you can add a rigorous course, retake a test, deepen an
					activity, or start something that matters. The same weakness spotted in October of senior
					year is just a fact you have to write around. The goal of this guide is to help you see
					those gaps a full year early, while they're still cheap to fix.
				</p>
			</section>

			<section>
				<h2 class="text-2xl font-bold tracking-tight text-slate-900">
					The 5 pillars admissions officers actually weigh
				</h2>
				<p class="mt-4">
					Holistic admissions sounds vague, but at most selective schools it reduces to a handful of
					pillars. Score yourself honestly on each &mdash; not against your friends, but against the
					students who were <em>admitted</em> to the schools you want.
				</p>
				<ul class="mt-4 space-y-3">
					<li class="flex gap-3">
						<span class="mt-1 font-bold text-[#0052CC]">1.</span>
						<span
							><strong class="text-slate-900">Academic rigor &amp; GPA.</strong> Not just your unweighted
							average, but how demanding your schedule is relative to what your school offers. Taking
							4 of a possible 12 APs reads very differently than 10 of 12.</span
						>
					</li>
					<li class="flex gap-3">
						<span class="mt-1 font-bold text-[#0052CC]">2.</span>
						<span
							><strong class="text-slate-900">Standardized testing.</strong> Where your SAT/ACT
							sits relative to a school's middle-50% range. Increasingly optional, but a strong score
							still moves the needle at most reaches.</span
						>
					</li>
					<li class="flex gap-3">
						<span class="mt-1 font-bold text-[#0052CC]">3.</span>
						<span
							><strong class="text-slate-900">Extracurricular depth.</strong> Depth and impact beat
							a long list. One activity where you built, led, or achieved something real outweighs
							ten club memberships.</span
						>
					</li>
					<li class="flex gap-3">
						<span class="mt-1 font-bold text-[#0052CC]">4.</span>
						<span
							><strong class="text-slate-900">Narrative &amp; essays.</strong> A coherent story
							that ties your interests together. Officers remember a through-line, not a résumé.</span
						>
					</li>
					<li class="flex gap-3">
						<span class="mt-1 font-bold text-[#0052CC]">5.</span>
						<span
							><strong class="text-slate-900">Context &amp; fit.</strong> How you compare within your
							own high school, region, and applicant pool &mdash; and whether the school reads you as
							genuinely interested.</span
						>
					</li>
				</ul>
			</section>

			<section>
				<h2 class="text-2xl font-bold tracking-tight text-slate-900">
					How to run your own gap analysis
				</h2>
				<p class="mt-4">
					A gap analysis is simple in principle: compare where you are now to where admitted
					students at your target schools were, pillar by pillar, and flag every gap. The trick is
					doing it honestly. Work through this checklist:
				</p>

				<div class="mt-6 rounded-2xl border border-slate-200 bg-slate-50 p-6">
					<h3 class="text-sm font-bold uppercase tracking-wide text-slate-500">
						Junior-year gap-analysis checklist
					</h3>
					<ul class="mt-4 space-y-3 text-slate-700">
						<li class="flex gap-3">
							<span class="text-[#0052CC]">&#10003;</span> Pull your school's course catalog and count
							how many of the most rigorous classes you've actually taken.
						</li>
						<li class="flex gap-3">
							<span class="text-[#0052CC]">&#10003;</span> Look up the middle-50% test range for each
							target school and mark where your current score falls.
						</li>
						<li class="flex gap-3">
							<span class="text-[#0052CC]">&#10003;</span> Rank your activities by real impact, not by
							title. Circle the one you'd talk about in an interview.
						</li>
						<li class="flex gap-3">
							<span class="text-[#0052CC]">&#10003;</span> Write one sentence describing your "hook"
							or narrative. If you can't, that's a gap.
						</li>
						<li class="flex gap-3">
							<span class="text-[#0052CC]">&#10003;</span> For each target school, note whether you're
							above, at, or below its admitted-student profile.
						</li>
					</ul>
				</div>

				<p class="mt-6">
					The single most common mistake here is comparing yourself to the average
					<em>applicant</em> instead of the average <em>admit</em>. The admit bar is meaningfully
					higher, and it's the only bar that matters. If doing this by hand feels imprecise, this is
					exactly the comparison
